DISPATCH = Path(__file__).resolve().parent.parent / "bin" / "sstack-dispatch"
RUNS = ".sstack/runs/"


class Warn(Exception):
    """Advice a static check prints as WARN: the exit code does not change."""

# ---- static checks ---------------------------------------------------------------------------

def _profile(root):
    """FAIL without ~/.sstack/config.toml; WARN on template files or config.toml keys home lacks."""
    require_profile(root, [("home", home_dir())])
    if items := CC.drift(home_dir()):
        raise Warn(f"drift: {', '.join(items)}; run sstack-config sync")
    return f"{home_dir()} has every template file and key"


def _loads(root):
    load(root), ades(root)
    return "config and ADEs parse"


def _legacy(root):
    old = legacy(root)
    if old:
        raise ConfigError(f"{', '.join(map(str, old))}: run `sstack-config migrate`")
    return "none"


def _roles(root):
    cfg = load(root)
    out = [f"{r} → {', '.join(A.key(m) for m in resolve(cfg, r) or []) or 'local'}" for r in sorted(cfg.get("role", {}))]
    out += [f"{r} → local (no roles/{r}.toml)" for r in sorted((READONLY_ROLES | {"implement"}) - set(cfg.get("role", {})))]
    out += [f"{v['id']} → {', '.join(A.key({**m, 'variant': None}) for m in R.variant_members(cfg, v)) or 'local'}"
            f" ({v['layer']})" for v in variants(root)]
    return "; ".join(out) or "no roles"


def _variants(root):
    """Stage variants: FAIL on a roles/implement/ folder (implement routes by [hint.*]); WARN on a
    variant .toml without its .md lens."""
    if bad := [str(d / "roles" / "implement") for _, d in layers(root) if (d / "roles" / "implement").is_dir()]:
        raise ConfigError(f"{', '.join(bad)}: implement has no variants; roles/implement/ is not read "
                          "(route implement with roles/implement.toml [hint.*])")
    vs = variants(root)
    if bare := [v["id"] for v in vs if not v["lens_path"]]:
        raise Warn("; ".join(f"{i} has no roles/{i}.md lens (variant still runs)" for i in bare))
    return f"{len(vs)}, each with a lens" if vs else "none"


def _used(cfg) -> set[str]:
    """Harnesses a role (any panel member) or a tier routes to."""
    used = {m["harness"] for r in cfg.get("role", {}) for m in resolve(cfg, r) or []}
    return used | {t["harness"] for t in cfg.get("tier", {}).values() if t.get("harness") not in (None, "local")}


def _clis(root):
    cfg = load(root)
    missing, seen = [], []
    for h in sorted(_used(cfg)):
        for k in ("headless", "headless_readonly"):
            argv = cfg["harness"].get(h, {}).get(k)
            if argv:
                seen.append(argv[0])
                if not shutil.which(argv[0]):
                    missing.append(f"{h}.{k}: {argv[0]}")
    if missing:
        raise ConfigError("not on PATH: " + ", ".join(missing))
    return ", ".join(sorted(set(seen))) or "no harness used"


def _ade(root):
    d = A.describe(*A.active(root, load(root), os.environ))
    return ", ".join(f"{k} {d[k]}" for k in ("name", "why", "delegate", "browser", "device", "capture", "note"))


def _hooks(root):
    bad = [str(a["hook_path"]) for a in ades(root) if a["hook_path"] and not os.access(a["hook_path"], os.X_OK)]
    if bad:
        raise ConfigError("not executable: " + ", ".join(bad))
    return "ok"


POINTER_FILES = ("~/.claude/CLAUDE.md", "~/.codex/AGENTS.md", "~/.cursor/AGENTS.md",
                 "~/.pi/agent/AGENTS.md")
POINTER = re.compile(r"<!-- sstack|start with the `?sstack`? skill|\bsstack first\b", re.I)
COMPETING = re.compile(r"\b(superpowers|oh-my-claudecode|OMC|oh-my-codex|OMX)\b.*\bfirst\b"
                       r"|without asking|do not stop to ask", re.I)


def _pointers(_root):
    """Read-only, advice only: does each agent's global instruction file point at sstack, and is a
    competing precedence rule above that pointer?
    # ponytail: first match in line order, plain text, no markdown awareness — a pointer inside a
    # comment or a rule phrased differently slips through. The WARN is wide on purpose: a human
    # reads it and these files are regenerated by other tools, so a false positive costs a glance.
    """
    home, ok, problems = Path.home(), [], []
    for rel in POINTER_FILES:
        f = home / rel[2:]
        try:
            if not f.is_file():
                continue
            lines = f.read_text(errors="replace").splitlines()
        except OSError as e:
            problems.append(f"{rel} unreadable ({e.strerror})")
            continue
        i = next((n for n, l in enumerate(lines) if POINTER.search(l)), None)
        if i is None:
            problems.append(f"{rel} missing")
            continue
        early = next(((n, l) for n, l in enumerate(lines[:i]) if COMPETING.search(l)), None)
        if early:
            n, l = early
            problems.append(f"{rel} late (line {n + 1}: {' '.join(l.split())[:60]})")
        else:
            ok.append(rel)
    if problems:
        raise Warn("; ".join(problems))
    return f"ok: {', '.join(ok)}" if ok else "no agent instruction files"


def _skills(root):
    cfg = load(root)
    # ponytail: any harness's dirs count; dispatch warns again when the member's harness lacks it
    dirs = S.path(cfg, root or Path.cwd(), list(cfg.get("harness", {})))
    names = S.configured(cfg)
    if missing := [n for n in names if not S.find(n, dirs)]:
        raise Warn(", ".join(missing))
    return ", ".join(names) or "none configured"


def _workflow(root):
    """Step folders (docs/spec/workflow.md): a chain that can run, and caps under the global ceiling."""
    specs, ceiling = step_folders(root), int(load(root).get("rules", {}).get("max_parallel", 4))
    on, chain, problems, warns = W.enabled(specs), W.order(specs), [], []
    for n in sorted(specs):
        s, spec = specs[n], specs[n]["spec"]
        after, on_fail = spec.get("after") or "", spec.get("on_fail")
        if after and after not in specs:
            problems.append(f"{n}: after {after!r} is not a step")
        if on_fail and on_fail not in specs:
            problems.append(f"{n}: on_fail {on_fail!r} is not a step")
        elif on_fail and on_fail not in on:
            problems.append(f"{n}: on_fail {on_fail!r} is disabled")
        files = [f for f, p in (("brief.md", s["brief"]), ("run.sh", s["run"])) if p]
        if not s["builtin"] and len(files) != 1:
            problems.append(f"steps/{n}: needs exactly one of brief.md or run.sh "
                            f"(has {' and '.join(files) or 'neither'})")
        if s["brief"] and not spec.get("role"):
            problems.append(f'steps/{n}: a brief.md needs role = "<role>"')
        level = spec.get("min_score")
        if level is not None and not (isinstance(level, int) and 1 <= level <= 10):
            problems.append(f"{n}: min_score {level} is outside 1..10")
        if n == "pr":
            if spec.get("gate") is False:
                problems.append("pr: gate = false; the yes before commit/push/PR cannot be disabled")
            if spec.get("enabled") is False:
                problems.append("pr: enabled = false; the PR step cannot be dropped")
        try:
            cap = int(spec.get("max_agents", 1))
        except (TypeError, ValueError):
            problems.append(f"{n}: max_agents {spec.get('max_agents')!r} is not an integer")
        else:
            if cap > ceiling:
                warns.append(f"{n}: max_agents {cap} > rules.max_parallel {ceiling}")
    if not chain:
        problems.append("no steps: defaults/steps/ is missing, or every step is disabled")
    firsts = [n for n in sorted(specs) if n in on and not (specs[n]["spec"].get("after") or "")]
    if len(firsts) > 1:
        problems.append(f"two first steps: {', '.join(firsts)} (one step needs after = \"\")")
    if left := sorted(on - set(chain)):
        problems.append(f"cycle: {', '.join(left)} is not reachable from the first step")
    if problems:
        raise ConfigError("; ".join(problems))
    if warns:
        raise Warn("; ".join(warns))
    return f"{len(chain)} steps: {' → '.join(chain)}"


def _overnight(root):
    """Validate the [overnight] policy read by `sstack-gate --merge` (docs/spec/config.md)."""
    ov = load(root).get("overnight")
    if not isinstance(ov, dict):
        raise ConfigError("overnight must be a table")
    problems = []
    merge = ov.get("merge")
    if merge not in ("never", "policy"):
        problems.append(f"merge {merge!r} is not never or policy")
    method = ov.get("method")
    if method not in ("merge", "squash", "rebase"):
        problems.append(f"method {method!r} is not merge, squash or rebase")
    score = ov.get("merge_min_score")
    if type(score) is not int or not 1 <= score <= 10:
        problems.append(f"merge_min_score {score!r} is outside 1..10")
    diff = ov.get("max_diff_lines")
    if type(diff) is not int or diff < 1:
        problems.append(f"max_diff_lines {diff!r} is below 1")
    never = ov.get("never_merge")
    if not isinstance(never, list) or any(not isinstance(x, str) for x in never):
        problems.append(f"never_merge {never!r} is not a list of strings")
    assumptions = ov.get("merge_with_assumptions")
    if type(assumptions) is not bool:
        problems.append(f"merge_with_assumptions {assumptions!r} is not a boolean")
    question = ov.get("on_question")
    if question not in ("decide", "park"):
        problems.append(f"on_question {question!r} is not decide or park")
    stuck = ov.get("on_stuck")
    if stuck not in ("draft", "park"):
        problems.append(f"on_stuck {stuck!r} is not draft or park")
    stop = ov.get("stop_at")
    if not isinstance(stop, str) or (stop and not re.fullmatch(r"(?:[01]\d|2[0-3]):[0-5]\d", stop)):
        problems.append(f"stop_at {stop!r} is not empty or HH:MM")
    if problems:
        raise ConfigError("; ".join(problems))
    if merge == "policy":
        return f"merge policy ({method}, score ≥ {score})"
    return "merge never"


CHECKS = [("profile", _profile), ("config loads", _loads), ("no legacy files", _legacy), ("roles resolve", _roles),
          ("stage variants", _variants), ("workflow", _workflow), ("overnight", _overnight),
          ("harness CLIs", _clis), ("active ADE", _ade), ("hooks executable", _hooks),
          ("entry pointers", _pointers),
          ("skills resolve", _skills)]


def static(root) -> int:
    code = 0
    for name, fn in CHECKS:
        try:
            print(f"PASS {name}: {fn(root)}")
        except Warn as e:
            print(f"WARN {name}: {e}")
        except (ConfigError, OSError, KeyError) as e:
            print(f"FAIL {name}: {e}")
            code = 1
    return code


# ---- smoke test ------------------------------------------------------------------------------

TITLE = "sstack smoke"  # the index lines' "task": smoke lines stay in the append-only index, tagged
SMOKE_DIR = re.compile(r"^smoke-\d{8}-\d{4}(?:-\d+)?$")
PRUNE_SKIP = {"index.jsonl", "reflect", "doctor"}


def _brief(d: Path, role: str, token: str) -> str:
    if role in READONLY_ROLES:
        return f"sstack smoke test. Reply with the line `CANARY {token}` and change nothing.\n"
    return (f"sstack smoke test. Write {d / 'canary.txt'} containing `{token}` (nothing else), "
            f"then reply with the line `CANARY {token}`. Change nothing else.\n")


def _dispatch(root: Path, *args) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(DISPATCH), *args], cwd=root, capture_output=True, text=True)


def _owned(root: Path, x) -> Path | None:
    """x resolved, when it is a direct child of <root>/.sstack/runs/doctor/ and not a symlink; else None."""
    p = Path(x)
    doctor = root.resolve() / RUNS / "doctor"  # unresolved below root: a symlinked runs/ or doctor/ never matches
    return p.resolve() if not p.is_symlink() and p.resolve().parent == doctor else None


def _run_owned(d: Path, x) -> Path | None:
    """x resolved, when it is inside smoke dir d and not a symlink; else None."""
    p = Path(x)
    r = p.resolve()
    return r if not p.is_symlink() and r != d.resolve() and r.is_relative_to(d.resolve()) else None


def _from_smoke(root: Path, d: Path, x: Path) -> bool:
    """x is a dispatch run dir whose report lives in this smoke dir d (run.json report_base)."""
    try:
        base = json.loads((x / "run.json").read_text())["report_base"]
    except (OSError, ValueError, KeyError, TypeError):
        return False
    return (root / base).resolve().parent == d.resolve()


def _cleanup(root: Path, d: Path, run_dirs: list[str]) -> bool:
    """Remove the smoke dir and the runs its smoke.json names — all or nothing: any path outside d
    or from another run → FAIL, nothing deleted. index.jsonl is never touched."""
    bad = [str(x) for x in run_dirs
           if not _run_owned(d, x) or not _from_smoke(root, d, _run_owned(d, x))]
    owned = _owned(root, d)
    if not owned or bad:
        print(f"FAIL cleanup: not a run of this smoke test under {root / RUNS / 'doctor'}, nothing deleted: "
              f"{', '.join(bad or [str(d)])}")
        return False
    shutil.rmtree(owned, ignore_errors=True)
    if not any(owned.parent.iterdir()):
        owned.parent.rmdir()
    return True


def smoke(root: Path) -> int:
    cfg = load(root)
    base = D.snapshot(root)
    doctor = root / RUNS / "doctor"
    doctor.mkdir(parents=True, exist_ok=True)
    stem, n = f"smoke-{time.strftime('%Y%m%d-%H%M')}", 1
    while True:
        d = doctor / (stem if n == 1 else f"{stem}-{n}")
        try:
            d.mkdir()
            break
        except FileExistsError:
            n += 1
    d = d.resolve()
    token = secrets.token_hex(8)
    state = {"token": token, "baseline": base, "roles": {}, "run_dirs": [], "errors": []}
    try:
        payloads = []
        for role in sorted(cfg.get("role", {})):
            brief, report = d / f"{role}.brief.md", d / f"{role}.md"
            brief.write_text(_brief(d, role, token))
            args = [role, "--brief", str(brief), "--report", str(report), "--title", TITLE, "--no-escalate"]
            args += ["--panel"] if role == "review" else []
            r = _dispatch(root, *args, "--route")
            if r.returncode == 3:
                print(f"SKIP {role}: runs locally", file=sys.stderr)  # stdout may be the exit-4 JSON
                continue
            try:
                state["roles"][role] = [c["member"] for c in json.loads(r.stdout)["calls"]]
            except (ValueError, KeyError, TypeError):
                state["errors"].append(f"{role}: sstack-dispatch --route exit {r.returncode}: {r.stderr.strip()}")
                continue
            seen = len(_lines(root))
            r = _dispatch(root, *args)
            if r.returncode == 4:
                p = json.loads(r.stdout)
                state["run_dirs"].append(p["run_dir"])
                payloads.append(p)
                continue
            # headless: this role's run dirs, from the lines it appended (other runs may append too)
            state["run_dirs"] += sorted({str(root / l["run_dir"]) for l in _lines(root)[seen:]
                                         if _mine(root, d, l) and "run_dir" in l} - set(state["run_dirs"]))
            if r.returncode not in (0, 1, 2):
                state["errors"].append(f"{role}: sstack-dispatch exit {r.returncode}: {r.stderr.strip()}")
        (d / "smoke.json").write_text(json.dumps(state, indent=2) + "\n")
        if payloads:
            print(json.dumps({"smoke_run_dir": str(d), "payloads": payloads,
                              "next": f"make every call and its `record`, then: sstack-doctor --smoke --check {d}"},
                             indent=2))
            return 4
    except BaseException:
        _cleanup(root, d, state["run_dirs"])
        raise
    return check(root, d)


def _lines(root: Path) -> list[dict]:
    p = root / D.INDEX
    out = []
    for l in p.read_text().splitlines() if p.is_file() else []:
        try:
            out.append(json.loads(l))
        except ValueError:
            pass
    return [l for l in out if isinstance(l, dict)]


def _mine(root: Path, d: Path, line: dict) -> bool:
    return isinstance(line.get("report"), str) and (root / line["report"]).resolve().is_relative_to(d)


def check(root: Path, d: Path) -> int:
    owned = _owned(root, d)
    if not owned or not SMOKE_DIR.fullmatch(owned.name):
        print(f"FAIL check: {d} is not a {root / RUNS / 'doctor'}/smoke-<YYYYMMDD-HHMM> dir")
        return 1
    d = owned
    state = json.loads((d / "smoke.json").read_text())
    ok = True
    try:
        token = state["token"]
        for e in state.get("errors", []):
            print(f"FAIL {e}")
            ok = False
        want = re.compile(rf"^\s*CANARY {re.escape(token)}\s*$", re.M)
        mine = [l for l in _lines(root) if _mine(root, d, l)]
        for role, members in state["roles"].items():
            report = d / f"{role}.md"
            ms = [A.unkey(m) for m in members]
            for m, um in zip(members, ms):
                h, _, model = m.partition("#")[0].partition("/")
                rp = D.report_path(report, um, ms)
                hit = [l for l in mine if l.get("harness") == h and l.get("model") == model
                       and l.get("variant") == um["variant"]
                       and (root / l["report"]).resolve() == rp]
                why = ("no index line" if not hit else f"exit {hit[-1].get('exit')}" if hit[-1].get("exit") != 0 else
                       f"no `CANARY {token}` line in {rp}" if not (rp.is_file() and want.search(rp.read_text())) else
                       f"readonly_warning {hit[-1]['readonly_warning']}" if hit[-1].get("readonly_warning") else None)
                cf = d / "canary.txt"
                if not why and role not in READONLY_ROLES and not (cf.is_file() and cf.read_text().strip() == token):
                    why = f"{cf.name} missing or wrong"
                print(f"{'FAIL' if why else 'PASS'} {role} {m}" + (f": {why}" if why else ""))
                ok = ok and not why
        # the smoke dir holds this invocation's runs; index.jsonl is held to append-only by tree_changes
        skip = [D.rel(root, d) + "/"]
        changed = D.tree_changes(root, state["baseline"], skip)
        print(f"{'FAIL' if changed else 'PASS'} tree unchanged" + (f": {', '.join(changed)}" if changed else ""))
        ok = ok and not changed
    finally:
        ok = _cleanup(root, d, state.get("run_dirs", [])) and ok
    return 0 if ok else 1


def prune(root: Path, days: int, yes: bool) -> int:
    """List (and with --yes delete) top-level runs older than `days` and finished, finished meaning
    progress.md has a line starting `done:` or does not exist."""
    runs = root / RUNS
    if not runs.is_dir():
        return 0
    if runs.resolve() != root.resolve() / RUNS:
        print(f"FAIL prune: {runs} resolves outside the repo, nothing deleted")
        return 1
    cutoff = time.time() - days * 86400
    for p in sorted(runs.iterdir(), key=lambda x: x.name):
        if p.name in PRUNE_SKIP or p.is_symlink() or not p.is_dir():
            continue
        progress = p / "progress.md"
        if progress.is_file():
            try:
                if not any(line.startswith("done:") for line in progress.read_text().splitlines()):
                    continue
            except OSError:
                continue
        stamps = [f.stat().st_mtime for f in p.rglob("*") if f.is_file()]
        newest = max(stamps, default=p.stat().st_mtime)
        if newest >= cutoff:
            continue
        print(D.rel(root, p))
        if yes:
            shutil.rmtree(p)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="sstack-doctor", description="Check the sstack config; --smoke runs "
                                 "one canary dispatch per routed member (ask the user first).")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--check", metavar="RUN_DIR", help="with --smoke: verify a tool-delegated smoke run")
    ap.add_argument("--prune-runs", metavar="DAYS", type=int,
                    help="list top-level runs older than DAYS; delete them with --yes")
    ap.add_argument("--yes", action="store_true", help="with --prune-runs: delete the listed runs")
    a = ap.parse_args(argv)
    root = git_root(Path.cwd())
    if a.prune_runs is not None:
        if root is None:
            print("FAIL prune: not in a git repo", file=sys.stderr)
            return 1
        return prune(root, a.prune_runs, a.yes)
    if not a.smoke:
        return static(root)
    if root is None:
        print("FAIL smoke: not in a git repo", file=sys.stderr)
        return 1
    try:
        return check(root, Path(a.check)) if a.check else smoke(root)
    except (ConfigError, OSError, ValueError) as e:
        print(f"FAIL smoke: {e}")
        return 1
