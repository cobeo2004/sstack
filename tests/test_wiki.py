import contextlib, io, os, shutil, subprocess

from helpers import REPO, TempEnv
import sstack_wiki as W


class WikiBase(TempEnv):
    def git(self, *a, cwd=None):
        return subprocess.run(["git", "-C", str(cwd or self.root), *a],
                              capture_output=True, text=True, check=True).stdout.strip()

    def commit(self, msg="i"):
        self.git("add", "-A")
        self.git("commit", "-qm", msg, "--allow-empty")
        return self.git("rev-parse", "--short", "HEAD")

    @property
    def d(self):
        return self.root / ".sstack/wiki"

    def page(self, name, body="", summary=None, d=None, **meta):
        fm = ""
        if summary is not None or meta:
            rows = ([f"summary: {summary}"] if summary is not None else []) + [f"{k}: {v}" for k, v in meta.items()]
            fm = "---\n" + "\n".join(rows) + "\n---\n\n"
        return self.write(d or self.d, f"{name}.md", fm + body)


class WikiCore(WikiBase):
    def test_wiki_dir_repo_and_global(self):
        self.assertEqual(W.wiki_dir("repo", self.root), self.root / ".sstack/wiki")
        self.assertEqual(W.wiki_dir("global", None), self.home / ".sstack/wiki")

    def test_global_follows_sstack_home(self):
        os.environ["SSTACK_HOME"] = str(self.home.parent / "sh")
        self.assertEqual(W.wiki_dir("global", None), self.home.parent / "sh" / "wiki")

    def test_worktree_reads_primary_wiki(self):
        self.commit()
        wt = (self.root.parent / "wt").resolve()
        self.git("worktree", "add", "-q", str(wt))
        self.page("a", "x")
        self.assertEqual(W.wiki_dir("repo", wt), self.root / ".sstack/wiki")
        self.page("x", "y", d=wt / ".sstack/wiki")
        self.assertEqual(W.wiki_dir("repo", wt), wt / ".sstack/wiki")

    def test_stale(self):
        self.write(self.root, "src/a.py", "1\n")
        s = self.commit()
        self.write(self.root, "src/a.py", "2\n")
        self.commit("c2")
        self.assertTrue(W.stale(["src/*.py"], s, self.root))
        self.assertFalse(W.stale(["docs/*"], s, self.root))
        self.assertFalse(W.stale([], s, self.root))
        self.assertFalse(W.stale(["*"], "deadbee", self.root))
        self.assertFalse(W.stale(["*"], None, self.root))


class WikiModel(WikiBase):
    def test_parse_frontmatter(self):
        p = W.parse_page(self.page("a", "body\n", summary="A thing", paths="lib/a/**, b.py", updated="3f9c2ab"))
        self.assertEqual((p.name, p.summary, p.paths, p.updated, p.has_meta),
                         ("a", "A thing", ["lib/a/**", "b.py"], "3f9c2ab", True))
        q = W.parse_page(self.page("b", "no meta\n"))
        self.assertEqual((q.summary, q.paths, q.updated, q.has_meta), ("", [], None, False))

    def test_links_skip_code_urls_and_outside(self):
        self.page("b", "x", summary="b")
        body = ("[b](b.md) `[c](c.md)`\n\n```\n[d](d.md)\n```\n\n[w](https://x/y.md) [s](b.md#sec)\n"
                "[o](../product.md) [i](index.md)\n")
        self.page("a", body, summary="a")
        a = W.load(self.d)["a"]
        self.assertEqual(a.links, ["b"])
        self.assertEqual(a.problems, [])

    def test_broken_and_cross_scope(self):
        rel = os.path.relpath(self.home / ".sstack/wiki/x.md", self.d)
        self.page("a", f"[g](gone.md) [h]({rel})\n", summary="a")
        self.assertEqual(W.load(self.d)["a"].problems, [("gone.md", "broken"), (rel, "cross-scope")])
        g = self.home / ".sstack/wiki"
        self.page("p", f"[r]({self.d / 'a.md'})\n", summary="p", d=g)
        self.assertEqual(W.load(g)["p"].problems, [(str(self.d / "a.md"), "cross-scope")])

    def test_lessons_is_a_node(self):
        self.page("auth", "x", summary="auth")
        self.write(self.d, "lessons.md", "# Lessons\n\n- [accepted] seen=1 id=L1 | see [auth](auth.md)\n")
        pages = W.load(self.d)
        self.assertEqual(pages["lessons"].summary, W.LESSONS_SUMMARY)
        self.assertEqual(pages["lessons"].links, ["auth"])
        self.assertEqual(W.backlinks(pages)["auth"], ["lessons"])

    def test_index_is_not_a_node(self):
        self.page("a", "x", summary="a")
        self.write(self.d, "index.md", "# Wiki index\n\n- [a](a.md)\n")
        self.assertNotIn("index", W.load(self.d))


INDEX_HEAD = ("# Wiki index\n\n"
              "<!-- generated by sstack-wiki index from page summaries; edit the pages, not this file -->\n\n")


class WikiCLI(WikiBase):
    def setUp(self):
        super().setUp()
        self._cwd = os.getcwd()
        os.chdir(self.root)
        self.page("a", "See [b](b.md).\n", summary="Page a")
        self.page("b", "See [a](a.md).\n", summary="Page b")
        self.write(self.d, "lessons.md", "# Lessons\n\n- [accepted] seen=1 id=L1 | x\n")

    def tearDown(self):
        os.chdir(self._cwd)
        super().tearDown()

    def cli(self, *a):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = W.main(list(a))
        return code, out.getvalue(), err.getvalue()

    def lint(self):
        code, out, _ = self.cli("lint")
        return code, out.splitlines()

    def test_index_exact_text(self):
        code, out, _ = self.cli("index")
        self.assertEqual(code, 0)
        self.assertEqual(out, f"wrote {self.d}/index.md (3 pages, 0 stale)\n")
        self.assertEqual((self.d / "index.md").read_text(), INDEX_HEAD +
                         "- [a](a.md) — Page a\n- [b](b.md) — Page b\n"
                         f"- [lessons](lessons.md) — {W.LESSONS_SUMMARY}\n")

    def test_index_empty_wiki(self):
        for p in self.d.glob("*.md"):
            p.unlink()
        self.cli("index")
        self.assertEqual((self.d / "index.md").read_text(), INDEX_HEAD)

    def test_index_marks_stale(self):
        self.write(self.root, "src/a.py", "1\n")
        sha = self.commit()
        self.page("s", "x\n", summary="Pinned", paths="src/*.py", updated=sha)
        self.write(self.root, "src/a.py", "2\n")
        self.commit("c2")
        code, out, _ = self.cli("index")
        self.assertIn("(4 pages, 1 stale)", out)
        self.assertIn("- [s](s.md) — Pinned [stale]\n", (self.d / "index.md").read_text())

    def test_index_no_wiki(self):
        shutil.rmtree(self.d)
        code, _, err = self.cli("index")
        self.assertEqual(code, 1)
        self.assertIn("no wiki at", err)

    def test_backlinks(self):
        self.assertEqual(self.cli("backlinks", "b")[:2], (0, "a.md\n"))
        self.assertEqual(self.cli("backlinks", "b.md")[:2], (0, "a.md\n"))
        self.assertEqual(self.cli("backlinks", "lessons")[:2], (0, ""))
        code, _, err = self.cli("backlinks", "nope")
        self.assertEqual(code, 1)
        self.assertIn("no page nope in", err)

    def test_lint_clean(self):
        self.cli("index")
        code, lines = self.lint()
        self.assertEqual(code, 0)
        self.assertEqual(lines[-1], "lint: 0 errors, 0 warnings")

    def test_lint_no_wiki(self):
        shutil.rmtree(self.d)
        self.assertEqual(self.lint(), (0, [f"lint: no wiki at {self.d}"]))

    def test_lint_broken_link(self):
        self.page("a", "See [b](b.md) and [g](gone.md).\n", summary="Page a")
        self.cli("index")
        code, lines = self.lint()
        self.assertEqual(code, 1)
        self.assertIn("ERROR a.md: broken link gone.md", lines)

    def test_lint_index_out_of_sync(self):
        self.cli("index")
        self.page("a", "See [b](b.md).\n", summary="Changed")
        code, lines = self.lint()
        self.assertEqual(code, 1)
        self.assertIn("ERROR index.md: out of sync; run sstack-wiki index", lines)
        (self.d / "index.md").unlink()
        code, lines = self.lint()
        self.assertEqual(code, 1)
        self.assertIn("ERROR index.md: out of sync; run sstack-wiki index", lines)

    def test_lint_stale_markers_only_warn(self):
        self.write(self.root, "src/a.py", "1\n")
        sha = self.commit()
        self.page("a", "See [b](b.md).\n", summary="Page a", paths="src/*.py", updated=sha)
        self.cli("index")
        self.write(self.root, "src/a.py", "2\n")
        self.commit("touch a pinned path")
        code, lines = self.lint()
        self.assertEqual(code, 0)
        self.assertIn("WARN index.md: stale markers out of date; run sstack-wiki index", lines)
        self.assertEqual(lines[-1], "lint: 0 errors, 1 warnings")

    def test_lint_cross_scope(self):
        self.page("a", "See [b](b.md) and [g](~/.sstack/wiki/git.md).\n", summary="Page a")
        self.cli("index")
        code, lines = self.lint()
        self.assertEqual(code, 1)
        self.assertIn("ERROR a.md: cross-scope link ~/.sstack/wiki/git.md", lines)

    def test_lint_warnings(self):
        self.page("c", "x\n" * 151, summary="s" * 121)
        self.page("e", "x\n")
        self.page("a", "See [b](b.md) and [e](e.md).\n", summary="Page a")
        self.cli("index")
        code, lines = self.lint()
        self.assertEqual(code, 0)
        for want in ("WARN c.md: orphan (no page links here)", "WARN c.md: summary is 121 chars (max 120)",
                     "WARN c.md: 155 lines (max 150)", "WARN e.md: no frontmatter summary"):
            self.assertIn(want, lines)

    def test_lint_skips_lessons_checks(self):
        self.write(self.d, "lessons.md", "- [pending] seen=1 id=L1 | x\n" * 200)
        self.cli("index")
        code, lines = self.lint()
        self.assertEqual(code, 0)
        self.assertEqual([l for l in lines if l.startswith("WARN lessons.md")], [])

    def test_lint_warns_two_lessons_files(self):
        self.write(self.root, ".sstack/lessons.md", "# Lessons\n")
        self.cli("index")
        _, lines = self.lint()
        self.assertIn(f"WARN lessons.md: old lessons file {self.root / '.sstack/lessons.md'} also exists; "
                      "the wiki copy wins", lines)

    def test_global_scope(self):
        sh = self.home.parent / "sh"
        os.environ["SSTACK_HOME"] = str(sh)
        self.page("g", "x\n", summary="Global", d=sh / "wiki")
        code, out, _ = self.cli("index", "--scope", "global")
        self.assertEqual(code, 0)
        self.assertIn("- [g](g.md) — Global\n", (sh / "wiki/index.md").read_text())

    def test_wrapper_runs(self):
        self.cli("index")
        r = subprocess.run([str(REPO / "bin/sstack-wiki"), "lint"], cwd=self.root, capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
